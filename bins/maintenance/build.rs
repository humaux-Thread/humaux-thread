//! `maintenance::build` — embeds the migration set: writes `$OUT_DIR/embedded_migrations.rs`, one
//!   `(migration_id, sql, manifest)` entry per `migrations/*.sql` in filename order, each body and its sibling
//!   `.manifest.toml` pulled in by `include_str!` so the release binary migrates without a source tree.
//! Depends-on: crates=[]; services=[]; env=[CARGO_MANIFEST_DIR, OUT_DIR]; modules=[]
//! Called-by: [cargo-build]
//! Invariants: [the table is exactly the directory: every `.sql`, sorted by filename, with `Some` manifest iff the
//!   sibling file exists; cargo reruns the script when anything under `migrations/` changes]
//! Spec: Baseline §46; ADR-0066 D-Q
//!
//! `include_str!` (not a copied string) keeps the bytes the compiler embeds identical to the files, so the runtime
//! FNV-1a checksum and the drift check see what a `--migrations-dir` run of the same tree would see.
use std::fmt::Write as _;
use std::path::Path;

fn main() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR");
    let dir = Path::new(&manifest_dir).join("../../migrations");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut sql: Vec<_> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("read {}: {e}", dir.display()))
        .map(|entry| entry.expect("migrations entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "sql"))
        .collect();
    sql.sort();
    let mut table = String::from(
        "/// `(migration_id, sql, manifest)` for every `migrations/*.sql`, in filename order (generated by build.rs).\n\
         static EMBEDDED_MIGRATIONS: &[(&str, &str, Option<&str>)] = &[\n",
    );
    for path in sql {
        let id = path
            .file_stem()
            .expect("file stem")
            .to_string_lossy()
            .into_owned();
        let manifest = path.with_extension("manifest.toml");
        let manifest = if manifest.exists() {
            format!("Some(include_str!({:?}))", manifest.display().to_string())
        } else {
            "None".to_owned()
        };
        let _ = writeln!(
            table,
            "    ({id:?}, include_str!({:?}), {manifest}),",
            path.display().to_string()
        );
    }
    table.push_str("];\n");
    let out = Path::new(&std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"))
        .join("embedded_migrations.rs");
    std::fs::write(&out, table).unwrap_or_else(|e| panic!("write {}: {e}", out.display()));
}
