/// The shim of T-J7: a `pgbackrest` earlier on `PATH` that fails only `verify`, and only while the test's flag file
/// exists; every other command (archive-push included) is the real binary.
const VERIFY_SHIM: &str = "#!/bin/sh\nif [ -e /var/lib/pgbackrest/fail-verify ]; then\n  for a in \"$@\"; do\n    [ \"$a\" = verify ] && { echo 'shim: verify fails'; exit 1; }\n  done\nfi\nexec /usr/bin/pgbackrest \"$@\"\n";

/// T-J7: two VERIFIED runs, then a run whose verification fails: nothing is expired, so `info` lists three fulls
/// (E16 invariant 5). Fault: run expire unconditionally → two fulls → red.
#[test]
fn a_failed_verification_expires_nothing() {
    use std::os::unix::fs::PermissionsExt;
    let Some(mut db) = throwaway::db("a_failed_verification_expires_nothing", RECEIPTS) else {
        return;
    };
    let Some(source) = Source::prepare("a_failed_verification_expires_nothing", "tj7") else {
        return;
    };
    let shim = source.dir.join("pgbackrest-shim");
    std::fs::write(&shim, VERIFY_SHIM).expect("shim");
    std::fs::set_permissions(&shim, std::fs::Permissions::from_mode(0o755)).expect("chmod shim");
    source.restart(&format!(
        "services:\n  pg:\n    volumes:\n      - type: bind\n        source: {}\n        target: /usr/local/bin/pgbackrest\n        read_only: true\n",
        shim.display()
    ));
    source.stanza_create();
    for _ in 0..2 {
        source.seed("w", 2);
        let out = source.maintenance(&db.maintenance_dsn, &["backup", "run"], &[]);
        assert_eq!(code(&out), 0, "{}", both(&out));
    }
    std::fs::write(source.repo_dir.join("fail-verify"), "").expect("flag");
    let out = source.maintenance(&db.maintenance_dsn, &["backup", "run"], &[]);
    assert_eq!(code(&out), 1, "{}", both(&out));
    assert_eq!(receipt(&out)["failure"], "verify_exit:1");
    assert_eq!(
        source.labels().len(),
        3,
        "a failed verification expired a set"
    );
    let outcomes: Vec<String> = receipts(&mut db).into_iter().map(|r| r.1).collect();
    assert_eq!(outcomes, ["VERIFIED", "VERIFIED", "FAILED"]);
}

/// The T-J8 / T-J13 layout: the repository filesystem is a capped tmpfs (PGDATA stays on its volume).
fn tmpfs_layout(bytes: u64, env: &str, archive: bool, tcp: bool) -> String {
    let listen = if tcp { "*" } else { "" };
    let archiving = if archive {
        ", -c, wal_level=replica, -c, archive_mode=on, -c, archive_timeout=3600s, -c, \"archive_command=pgbackrest --stanza=humaux archive-push %p\""
    } else {
        ", -c, archive_mode=off"
    };
    format!(
        "services:\n  pg:\n    environment:\n{env}    volumes:\n      - type: tmpfs\n        target: /var/lib/pgbackrest\n        tmpfs:\n          size: {bytes}\n\
         \x20   command: [postgres, -c, max_wal_size=64MB, -c, min_wal_size=32MB{archiving}, -c, \"listen_addresses={listen}\"]\n"
    )
}

/// Bytes of a `du -sk` / `df -Pk` style figure inside `pg`.
fn kib(source: &Source, script: &str) -> i64 {
    source
        .sh(script)
        .trim()
        .parse::<i64>()
        .expect("a KiB figure")
        * 1024
}

/// Headroom the filler leaves unallocated: the repository can grow between the `df` reading and `fallocate` (an
/// in-flight `archive-push` writes a WAL segment), so requesting the whole observed difference can ask for bytes
/// already gone and fail ENOSPC (run 40058742422).
const FILLER_HEADROOM: i64 = 8 << 20;

/// Bytes `fallocate` must request so that `free` bytes remain after the allocation plus [`FILLER_HEADROOM`].
fn filler_bytes(now: i64, free: i64) -> i64 {
    now - free - FILLER_HEADROOM
}

/// Fills the repository filesystem with a test-owned file outside `repo/` down to `free` bytes plus
/// [`FILLER_HEADROOM`] that a concurrent repository write may take before the allocation lands.
fn fill_to(source: &Source, free: i64) {
    let now = kib(
        source,
        "df -Pk /var/lib/pgbackrest | tail -1 | awk '{print $4}'",
    );
    let filler = filler_bytes(now, free);
    assert!(
        filler > 0,
        "tmpfs too small: free {now} <= {free} + {FILLER_HEADROOM}"
    );
    source.sh(&format!("fallocate -l {filler} /var/lib/pgbackrest/filler"));
}

/// #273 F5: the filler never requests the whole observed difference, so a repository write between `df` and
/// `fallocate` cannot make the request exceed the free space (run 40058742422).
#[test]
fn flake_273_filler_keeps_headroom_for_a_concurrent_repository_write() {
    // The T-J13 96 MiB tmpfs with its 4 MiB target: the filler holds 8 MiB back, never the 92 MiB difference.
    assert_eq!(filler_bytes(96 << 20, 4 << 20), (96 - 4 - 8) << 20);
    // The T-J8 256 MiB tmpfs: still exactly the observed difference minus the fixed headroom.
    assert_eq!(filler_bytes(256 << 20, 32 << 20), (256 - 32 - 8) << 20);
}

/// T-J8 (10.11 I): PGDATA on its volume, the repository on a 256 MiB tmpfs, a database of >= 64 MiB seeded with
/// archiving off, a filler that leaves less free than the first-backup estimate plus MIN_FREE: `backup run` refuses
/// `budget_free_floor` (exit 3) before writing — one FAILED receipt with a NULL label and the budget numbers, `repo/`
/// unchanged, PostgreSQL untouched and writable; with REPO_MAX = the current repository bytes it refuses
/// `budget_repo_max`. Fault: skip the estimate → the backup writes into the tmpfs (ENOSPC, exit 1, or changed
/// `repo/` bytes) → red.
#[test]
fn a_backup_that_would_break_the_budget_is_refused_before_writing() {
    const MIN_FREE: i64 = 32 << 20;
    let Some(mut db) = throwaway::db(
        "a_backup_that_would_break_the_budget_is_refused_before_writing",
        RECEIPTS,
    ) else {
        return;
    };
    let env = "      PGBACKREST_COMPRESS_TYPE: none\n";
    let Some(source) = Source::start(
        "a_backup_that_would_break_the_budget_is_refused_before_writing",
        "tj8",
        &tmpfs_layout(256 << 20, env, false, false),
    ) else {
        return;
    };
    source.seed("w", 72);
    source.restart(&tmpfs_layout(256 << 20, env, true, false));
    source.own_repo_mount();
    source.stanza_create();
    let estimate = kib(
        &source,
        "du -sk /var/lib/postgresql/18/docker/base | cut -f1",
    );
    assert!(estimate >= 64 << 20, "database >= 64 MiB: {estimate}");
    // `fill_to` leaves `FILLER_HEADROOM` unallocated, so ask that much below the 8 MiB safety margin this test
    // wants between the estimate and the floor.
    fill_to(&source, estimate + MIN_FREE - (8 << 20) - FILLER_HEADROOM);
    let repo_before = source.sh("du -sk /var/lib/pgbackrest/repo | cut -f1");
    let started = source.psql("select pg_postmaster_start_time()");

    let out = source.maintenance(
        &db.maintenance_dsn,
        &["backup", "run"],
        &[(
            "HUMAUX_MAINTENANCE_BACKUP_MIN_FREE_BYTES",
            MIN_FREE.to_string(),
        )],
    );
    let all = both(&out);
    assert_eq!(code(&out), 3, "{all}");
    assert!(
        String::from_utf8_lossy(&out.stdout).contains("budget_free_floor:"),
        "{all}"
    );
    assert!(!all.contains("No space left on device"), "{all}");
    let row = db
        .client()
        .query_one(
            "SELECT outcome, failure LIKE 'budget_free_floor:%', backup_label IS NULL, repo_bytes IS NOT NULL, \
                    repo_free_bytes IS NOT NULL, estimate_bytes IS NOT NULL FROM ops.backup_receipts",
            &[],
        )
        .expect("exactly one receipt");
    assert_eq!(row.get::<_, String>(0), "FAILED");
    for i in 1..=5 {
        assert!(row.get::<_, bool>(i), "receipt column {i}");
    }
    assert_eq!(
        source.sh("du -sk /var/lib/pgbackrest/repo | cut -f1"),
        repo_before,
        "repo/ untouched"
    );
    assert_eq!(
        source.psql("select pg_postmaster_start_time()"),
        started,
        "PostgreSQL untouched"
    );
    source.psql("insert into w values (-1, 'still writable')");

    let repo_bytes = kib(&source, "du -sk /var/lib/pgbackrest/repo | cut -f1");
    let out = source.maintenance(
        &db.maintenance_dsn,
        &["backup", "run"],
        &[
            (
                "HUMAUX_MAINTENANCE_BACKUP_REPO_MAX_BYTES",
                repo_bytes.to_string(),
            ),
            ("HUMAUX_MAINTENANCE_BACKUP_MIN_FREE_BYTES", "1".to_owned()),
        ],
    );
    assert_eq!(code(&out), 3, "{}", both(&out));
    assert!(
        String::from_utf8_lossy(&out.stdout).contains("budget_repo_max:"),
        "{}",
        both(&out)
    );
    assert_eq!(
        source.sh("du -sk /var/lib/pgbackrest/repo | cut -f1"),
        repo_before,
        "repo/ untouched"
    );
    assert!(source.labels().is_empty(), "no set was written");
}

/// T-J13 (10.11 I, live leg of the WAL bound): the repository on a 96 MiB tmpfs left nearly full, the archive queue
/// capped at 64 MiB: archiving fails and PostgreSQL does not — every INSERT succeeds, the postmaster never restarts,
/// segments are dropped past the cap and `pg_wal` stays bounded (spike SP-10 measured the bound: queue max +
/// max_wal_size + three segments; SP-10 measured 144 MiB under the same caps). The latch (S6, 10.11 I): one
/// DR_EVIDENCE pass of the real daemon against the scratch cluster after the first failures reads
/// `wal_archive_failing 1`; after the drops (which PostgreSQL counts as archived) a second pass still reads 1 from
/// `ops.wal_archive_failures` (one row for the incident). Fault: drop the queue-max override (the conf's 2 GiB lets
/// `pg_wal` grow with every round) → red. The latch's own fault (a non-latched expression) is T-K3''s: here the
/// archiver is usually still failing at the second pass (measured), so that fault does not show at this leg.
#[test]
fn a_full_repo_filesystem_stops_archiving_not_postgres() {
    const BOUND: i64 = (64 + 64 + 3 * 16) << 20;
    let env = "      PGBACKREST_ARCHIVE_PUSH_QUEUE_MAX: 64MiB\n";
    let Some(source) = Source::start(
        "a_full_repo_filesystem_stops_archiving_not_postgres",
        "tj13",
        &tmpfs_layout(96 << 20, env, true, true),
    ) else {
        return;
    };
    source.own_repo_mount();
    // ADR-0064 D-K: the DR_EVIDENCE passes need the schema and a role_maintenance login on this scratch cluster.
    source.psql("CREATE DATABASE humaux_thread");
    // dep: PostgreSQL(owner) — migrate the scratch cluster's database (never the dev cluster)
    let mut owner = postgres::Client::connect(&source.owner_dsn("humaux_thread"), postgres::NoTls)
        .expect("scratch owner");
    throwaway::migrate_all(&mut owner);
    let password = random_hex();
    owner
        .batch_execute(&format!(
            "ALTER ROLE role_maintenance PASSWORD '{password}'"
        ))
        .expect("role_maintenance login");
    let dsn = format!(
        "postgres://role_maintenance:{password}@127.0.0.1:{}/humaux_thread",
        source.env_value("HUMAUX_PG_PORT")
    );
    source.stanza_create();
    fill_to(&source, 4 << 20);
    let started = source.psql("select pg_postmaster_start_time()");
    let mut max_wal = 0_i64;
    let mut round = |n: u32| {
        for _ in 0..n {
            source.seed("b", 12);
            source.psql("select pg_switch_wal()");
            let w: i64 = source
                .psql("select sum(size) from pg_ls_waldir()")
                .parse()
                .expect("pg_wal bytes");
            max_wal = max_wal.max(w);
        }
    };
    round(2);
    let failing = (0..20).any(|_| {
        std::thread::sleep(Duration::from_millis(500));
        source.psql("select coalesce(last_failed_time > coalesce(last_archived_time, '-infinity'), false) from pg_stat_archiver")
            == "t"
    });
    assert!(
        failing,
        "archiving fails once the repository filesystem is full"
    );
    // dep: subprocess(humaux-maintenance) — one DR_EVIDENCE pass of the real daemon against the scratch cluster
    let first = throwaway::dr_evidence_pass(&dsn, &source.repo_dir);
    assert_eq!(
        throwaway::sample_value(&first, "wal_archive_failing"),
        Some(1.0),
        "the first pass latches: {first}"
    );
    round(14);
    assert_eq!(
        source.psql("select pg_postmaster_start_time()"),
        started,
        "PostgreSQL never restarted"
    );
    assert!(max_wal <= BOUND, "pg_wal bounded: {max_wal} > {BOUND}");
    assert!(
        source.logs().contains("because archive queue exceeded"),
        "segments were dropped at the cap"
    );
    let second = throwaway::dr_evidence_pass(&dsn, &source.repo_dir);
    assert_eq!(
        throwaway::sample_value(&second, "wal_archive_failing"),
        Some(1.0),
        "still latched after the drops: {second}"
    );
    let rows: i64 = owner
        .query_one("SELECT count(*) FROM ops.wal_archive_failures", &[])
        .expect("latch rows")
        .get(0);
    assert_eq!(rows, 1, "one row for the incident");
}

/// T-J14 (10.11 A): with the repository mount on the pgdata volume, `backup check` exits 1 and `backup run` exits 3,
/// both `repo_shares_pgdata_fs`, and nothing is written under `repo/` by either arm. Fault: remove the `st_dev`
/// comparison → check runs pgBackRest / run backs up → red.
#[test]
fn backup_refuses_a_repo_on_the_pgdata_filesystem() {
    let Some(mut db) = throwaway::db("backup_refuses_a_repo_on_the_pgdata_filesystem", RECEIPTS)
    else {
        return;
    };
    let extra = "services:\n  pg:\n    volumes:\n      - pgdata:/var/lib/pgbackrest\n";
    let Some(source) = Source::start(
        "backup_refuses_a_repo_on_the_pgdata_filesystem",
        "tj14",
        extra,
    ) else {
        return;
    };
    let listing = "find /var/lib/pgbackrest/repo 2>/dev/null | sort | wc -l";
    let before = source.sh(listing);
    let check = source.maintenance("", &["backup", "check"], &[]);
    assert_eq!(code(&check), 1, "{}", both(&check));
    assert_eq!(receipt(&check)["failure"], "repo_shares_pgdata_fs");
    assert_local_only(&receipt(&check));
    let run = source.maintenance(&db.maintenance_dsn, &["backup", "run"], &[]);
    assert_eq!(code(&run), 3, "{}", both(&run));
    assert_eq!(receipt(&run)["reason"], "repo_shares_pgdata_fs");
    assert_eq!(source.sh(listing), before, "nothing written under repo/");
    assert_eq!(
        receipts(&mut db),
        [(
            None,
            "FAILED".to_owned(),
            Some("repo_shares_pgdata_fs".to_owned())
        )]
    );
}

/// T-J9 (+10.11 I): three VERIFIED runs leave exactly the two newest fulls in `info`, and `backup status` reports the
/// PITR window from the older of those two (not from the first receipt). Faults: `repo1-retention-full=3` → three
/// fulls → red; the window computed from receipts only → the first set's start → red.
#[test]
fn expire_keeps_exactly_the_two_newest_verified_fulls() {
    let Some(mut db) = throwaway::db(
        "expire_keeps_exactly_the_two_newest_verified_fulls",
        RECEIPTS,
    ) else {
        return;
    };
    let Some(source) = Source::start(
        "expire_keeps_exactly_the_two_newest_verified_fulls",
        "tj9",
        "",
    ) else {
        return;
    };
    source.stanza_create();
    let mut made = Vec::new();
    for _ in 0..3 {
        source.seed("w", 2);
        let out = source.maintenance(&db.maintenance_dsn, &["backup", "run"], &[]);
        assert_eq!(code(&out), 0, "{}", both(&out));
        let r = receipt(&out);
        made.push((
            r["backup_label"].as_str().expect("label").to_owned(),
            r["backup_started_at"].clone(),
        ));
    }
    assert_eq!(
        source.labels(),
        [made[1].0.clone(), made[2].0.clone()],
        "exactly the two newest"
    );
    let out = source.maintenance(&db.maintenance_dsn, &["backup", "status"], &[]);
    assert_eq!(code(&out), 0, "{}", both(&out));
    assert_eq!(
        receipt(&out)["pitr_window_unbroken_since"],
        made[1].1,
        "window from the older set present"
    );
    assert_eq!(count(&mut db, "ops.backup_receipts"), 3);
}

/// T-J12 (+10.11 G, I): `backup check` on the encrypted stanza prints `repo_cipher=aes-256-cbc` and `weak_subkeys=0`,
/// exits 0, and no subkey (a 64-character base64 run) appears anywhere in its output. Faults: print the `repo-get`
/// output → red; `repo1-cipher-type=none` → `repo_not_encrypted` → red.
#[test]
fn check_counts_weak_subkeys_without_printing_them() {
    let Some(source) = Source::start(
        "check_counts_weak_subkeys_without_printing_them",
        "tj12",
        "",
    ) else {
        return;
    };
    source.stanza_create();
    let out = source.maintenance("", &["backup", "check"], &[]);
    let all = both(&out);
    assert_eq!(code(&out), 0, "{all}");
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(
        stdout.lines().any(|l| l == "repo_cipher=aes-256-cbc"),
        "{all}"
    );
    assert!(stdout.lines().any(|l| l == "weak_subkeys=0"), "{all}");
    assert_local_only(&receipt(&out));
    let mut run = 0;
    for b in all.bytes() {
        run = if b.is_ascii_alphanumeric() || b == b'+' || b == b'/' || b == b'=' {
            run + 1
        } else {
            0
        };
        assert!(
            run < 64,
            "a 64-character base64 run (a subkey?) in the output"
        );
    }
}
